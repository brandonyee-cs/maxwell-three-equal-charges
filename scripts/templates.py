"""Shared text of the 2-D hypotheses (used for both the transfer lemma and H1/H2)."""
X = "![0, 1, u] j"; Y = "![0, 0, w] j"
D1 = f"(p.1 - {X})"; D2 = f"(p.2 - {Y})"
RR = f"Real.sqrt ({D1}^2 + {D2}^2)"
COND = f"(∀ j, {D1}^2 + {D2}^2 ≠ 0)"
EQ1 = f"∑ j, q j * {D1} / {RR}^3 = 0"
EQ2 = f"∑ j, q j * {D2} / {RR}^3 = 0"
HXX = f"(∑ j, q j * (2 * {D1}^2 - {D2}^2) / {RR}^5)"
HYY = f"(∑ j, q j * (2 * {D2}^2 - {D1}^2) / {RR}^5)"
HXY = f"(∑ j, q j * (3 * {D1} * {D2}) / {RR}^5)"
NONDEG = f"(∀ p : ℝ × ℝ, {COND} →\n      {EQ1} →\n      {EQ2} →\n      {HXX} *\n        {HYY} -\n        {HXY}^2 ≠ 0)"
SET = f"{{p : ℝ × ℝ | {COND} ∧\n      {EQ1} ∧\n      {EQ2}}}"
